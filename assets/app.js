let lang = localStorage.getItem('arda-lang') || 'de';
if (!translations[lang]) lang = 'de';
const galleryGrid = document.getElementById('galleryGrid');
const imageCount = 22;

function buildGallery() {
  galleryGrid.innerHTML = '';
  for (let i = 1; i <= imageCount; i++) {
    const item = document.createElement('figure');
    item.className = 'gallery-item';
    const img = document.createElement('img');
    img.loading = 'lazy';
    img.src = `assets/images/hair-${String(i).padStart(2,'0')}.jpg`;
    const labels = {de:'ARDA Hair Look', tr:'ARDA Hair görünüm', en:'ARDA Hair look'};
    img.alt = `${labels[lang]} ${i}`;
    item.appendChild(img);
    item.onclick = () => openLightbox(img.src);
    galleryGrid.appendChild(item);
  }
}

function applyLang() {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.innerHTML = translations[lang][key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = translations[lang][el.dataset.i18nPlaceholder];
  });
  document.querySelectorAll('.lang-option').forEach(btn => btn.classList.toggle('active', btn.dataset.lang === lang));
  localStorage.setItem('arda-lang', lang);
  buildGallery();
}

document.querySelectorAll('.lang-option').forEach(btn => {
  btn.addEventListener('click', () => { lang = btn.dataset.lang; applyLang(); });
});

const backdrop = document.getElementById('backdrop');
function openDrawer(id){ document.getElementById(id).classList.add('open'); backdrop.classList.add('show'); }
function closeDrawers(){ document.querySelectorAll('.drawer').forEach(x => x.classList.remove('open')); backdrop.classList.remove('show'); }
document.getElementById('menuBtn').onclick = () => openDrawer('menuDrawer');
document.getElementById('cartBtn').onclick = () => openDrawer('cartDrawer');
document.getElementById('favBtn').onclick = () => openDrawer('favDrawer');
document.querySelectorAll('[data-close]').forEach(b => b.onclick = closeDrawers);
document.querySelectorAll('.drawer a').forEach(a => a.onclick = closeDrawers);
backdrop.onclick = closeDrawers;

const lightbox = document.getElementById('lightbox');
const lightboxImg = document.getElementById('lightboxImg');
function openLightbox(src){ lightboxImg.src = src; lightbox.classList.add('show'); }
document.getElementById('lightboxClose').onclick = () => lightbox.classList.remove('show');
lightbox.onclick = e => { if (e.target === lightbox) lightbox.classList.remove('show'); };

document.getElementById('notifyForm').onsubmit = e => {
  e.preventDefault();
  document.getElementById('formMsg').textContent = translations[lang].thanks;
  e.target.reset();
};

const observer = new IntersectionObserver(entries => entries.forEach(e => {
  if (e.isIntersecting) e.target.classList.add('visible');
}), {threshold:.1});
document.querySelectorAll('.reveal').forEach(x => observer.observe(x));
applyLang();
