async function getMainCartLiveStock(item) {

  if (!item) return null;

  if (item.variantId) {

    const { data, error } =
      await shopDb
        .from('product_variants')
        .select('stock')
        .eq('id', item.variantId)
        .maybeSingle();

    if (!error && data) {
      return Math.max(
        0,
        Number(data.stock || 0)
      );
    }

  }

  if (item.productId) {

    const { data, error } =
      await shopDb
        .from('products')
        .select('stock')
        .eq('id', item.productId)
        .maybeSingle();

    if (!error && data) {
      return Math.max(
        0,
        Number(data.stock || 0)
      );
    }

  }

  return null;
}


window.changeMainCartQuantity =
async function(index, delta) {

  const cart =
    getSavedCart();

  const item =
    cart[index];

  if (!item) return;

  const current =
    Number(item.quantity || 1);

  const change =
    Number(delta || 0);

  const next =
    current + change;

  if (next <= 0) {

    cart.splice(index, 1);

  } else if (change > 0) {

    const stock =
      await getMainCartLiveStock(item);

    if (stock === null) {
      return;
    }

    item.quantity =
      Math.min(
        stock,
        next
      );

  } else {

    item.quantity = next;

  }

  localStorage.setItem(
    'ardaHairCart',
    JSON.stringify(cart)
  );

  renderMainCart();

};


